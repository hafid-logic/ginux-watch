#!/usr/bin/env python3
"""test-report-lint.py — offline tests for scripts/report_lint.py (v7.5 clause 1 + v7.6-1).

Zero network, zero secrets. Covers:
  L1  fixture matrix: per-clause positives fire their clause — ERROR clauses
      (a..f) produce verdict FAIL; WARN clauses (g,h) produce warns without
      failing (v7.6-1 severity model); negatives PASS clean.
      Fixtures: eval/supervisor-defects/lint/fixtures/ (generated by
      scripts/gen_lint_fixtures.sh)
  L1b v7.6-1 calibration fixtures: g2 (current-state claim without
      base_head warns; historical record without claims does not), h2
      (h enforced from v7.5-era reports, skipped pre-v7.5).
  L2  defect-benchmark integration: the 8 defect cases (أ..ح) + 4 clean
      controls materialized from eval/supervisor-defects/cases/*.yaml —
      expectations are the 2026-11-12 measured matrix REMAPPED to the
      v7.6-1 severity model (ERROR/WARN) and era rules:
        - defect cases 01..08 materialize as v7.5-era (directive: v7.5)
        - controls 09..12 materialize pre-v7.5 (directive: v6.8) — h is
          era-gated off, matching their real vintage
        - defect-07 (ز): raw input has no base_head and no current-state
          claim -> no warn under the v7.6-1 g refinement (recorded change)
  L3  --fix appends the lint line into the front-matter; idempotent
  L4  --check fails on missing/stale lint line, passes on a fresh one
  L5  exit codes: 0 pass-or-warn-only / 1 error fail / 2 usage
  L6  --json summary shape (failed = ERROR clauses, warns separate)
  L7  path placeholder normalization (state/quota-google-<date>.json)
  L8  reused gates: TOKEN_PATTERNS/CJK_RANGES imported single-source
  L9  lint-line compatibility: legacy v7.5 lines accepted leniently under
      --check; v7.6 lines compared strictly (warn section included)
  L10 severity exits: warn-only report exits 0; error report exits 1

Run: python3 team/scripts/test-report-lint.py
"""
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
import report_lint as rl  # noqa: E402

PASS, FAIL = 0, 0
def ok(name):
    global PASS
    PASS += 1
    print("ok  %s" % name)
def no(name, msg=""):
    global FAIL
    FAIL += 1
    print("FAIL %s %s" % (name, msg))

def subprocess_lint(args):
    return subprocess.run([sys.executable, str(REPO / "scripts" / "report_lint.py"), *args],
                          capture_output=True, text=True)

# ---------- L1 fixture matrix (v7.6-1 severity model) ----------
FX = REPO / "eval/supervisor-defects/lint/fixtures"
ERROR_POS = ["a", "b", "c", "d", "e", "f"]
for clause in ERROR_POS:
    v, failed, warns, _ = rl.lint_text((FX / ("%s-pos.md" % clause)).read_text())
    if v == "FAIL" and clause in failed and not warns:
        ok("L1 %s-pos ERROR fails %s" % (clause, clause))
    else:
        no("L1 %s-pos" % clause, "verdict=%s failed=%s warns=%s" % (v, failed, warns))
for clause in ("g", "h"):
    v, failed, warns, _ = rl.lint_text((FX / ("%s-pos.md" % clause)).read_text())
    if v == "PASS" and not failed and clause in warns:
        ok("L1 %s-pos WARN-only (%s in warns, verdict PASS)" % (clause, clause))
    else:
        no("L1 %s-pos" % clause, "verdict=%s failed=%s warns=%s" % (v, failed, warns))
for clause in ("a", "b", "c", "d", "e", "f", "g", "h"):
    v, failed, warns, _ = rl.lint_text((FX / ("%s-neg.md" % clause)).read_text())
    if v == "PASS" and not failed and not warns:
        ok("L1 %s-neg passes clean" % clause)
    else:
        no("L1 %s-neg" % clause, "failed=%s warns=%s" % (failed, warns))

# ---------- L1b v7.6-1 calibration fixtures ----------
v, failed, warns, _ = rl.lint_text((FX / "g2-pos.md").read_text())
if v == "PASS" and not failed and warns == ["g"]:
    ok("L1b g2-pos: current-state claim without base_head -> warn g only")
else:
    no("L1b g2-pos", "verdict=%s failed=%s warns=%s" % (v, failed, warns))
v, failed, warns, _ = rl.lint_text((FX / "g2-neg.md").read_text())
if v == "PASS" and not failed and not warns:
    ok("L1b g2-neg: historical record without claims -> no g")
else:
    no("L1b g2-neg", "failed=%s warns=%s" % (failed, warns))
v, failed, warns, _ = rl.lint_text((FX / "h2-v75-pos.md").read_text())
if v == "PASS" and not failed and warns == ["h"]:
    ok("L1b h2-v75-pos: v7.5-era sandbox path -> warn h only")
else:
    no("L1b h2-v75-pos", "failed=%s warns=%s" % (failed, warns))
v, failed, warns, _ = rl.lint_text((FX / "h2-pre75-neg.md").read_text())
if v == "PASS" and not failed and not warns:
    ok("L1b h2-pre75-neg: pre-v7.5 era -> h skipped")
else:
    no("L1b h2-pre75-neg", "failed=%s warns=%s" % (failed, warns))
if rl.report_era("x", "outbox/20261112-0046Z-s58.md") == "v75" and \
   rl.report_era("x", "outbox/20261108-1930Z-s57.md") == "pre75":
    ok("L1b report_era filename dating (20261112 cutoff)")
else:
    no("L1b report_era dating")

# ---------- L1c b mention-context skips (v7.6-1 calibration) ----------
B_BASE = "---\nid: t\nbase_head: 394985f\n---\n\n"
v, failed, warns, _ = rl.lint_text(B_BASE + "السياسة: التقرير أول سطر فيه `circuit_breaker: TRIPPED` عند الرد.\n")
if "b" not in failed and not warns:
    ok("L1c b: code-span format reference skipped")
else:
    no("L1c b code-span", "failed=%s warns=%s" % (failed, warns))
v, failed, warns, _ = rl.lint_text(B_BASE + "# التقرير — تنفيذ مع إشعار TRIPPED وإعادة كتابة cron\n")
if "b" not in failed and not warns:
    ok("L1c b: heading topic mention skipped")
else:
    no("L1c b heading", "failed=%s warns=%s" % (failed, warns))
v, failed, warns, _ = rl.lint_text(B_BASE + "التغيّر المعروف لا يفتح TRIPPED جديدًا إلا بإعادة بناء notify-state.\n")
if "b" not in failed and not warns:
    ok("L1c b: negated mention skipped")
else:
    no("L1c b negated", "failed=%s warns=%s" % (failed, warns))
v, failed, warns, _ = rl.lint_text(B_BASE + "قاطع PR#207: TRIPPED — رد جديد مرصود اليوم.\n")
if "b" in failed:
    ok("L1c b: real prose claim still fires")
else:
    no("L1c b real claim", "failed=%s" % failed)

# ---------- L2 defect-benchmark integration (v7.6-1 remap, 2026-11-12) ----------
import yaml  # noqa: E402
# (errors, warns) under the v7.6-1 severity model:
#   ERROR a..f, WARN g..h; h era-gated off pre-v7.5.
MEASURED = {
    "defect-01-clear-from-static-html": (["a"], ["h"]),
    "defect-02-verdict-on-old-known-responses": (["a"], ["h"]),
    "defect-03-patch-target-unverified-on-main": ([], []),
    "defect-04-failed-run-as-healthy-heartbeat": (["d"], []),
    "defect-05-cjk-language-slip": (["e"], []),
    "defect-06-token-in-conversation": ([], ["h"]),
    "defect-07-push-from-stale-base-after-rotation": ([], []),
    "defect-08-agentbox-paths-as-repo-paths": ([], ["h"]),
    "defect-09-clean-control-s49": ([], []),
    "defect-10-clean-control-s51": (["a"], []),
    "defect-11-clean-control-s56": ([], []),
    "defect-12-clean-control-s57": ([], []),
}
CASES = REPO / "eval/supervisor-defects/cases"
for name in sorted(MEASURED):
    doc = yaml.safe_load((CASES / ("%s.yaml" % name)).read_text())
    t = doc.get("defect_type")
    era = "v6.8" if int(name.split("-")[1]) >= 9 else "v7.5"
    if t == "ز":
        # raw incident input (as measured 2026-11-12): no injected head
        text = doc.get("input", "")
    else:
        text = "---\nid: materialized\ndefect_type: %s\ndirective: %s\nbase_head: 394985f\n---\n\n%s" % (
            t, era, doc.get("input", ""))
    v, failed, warns, _ = rl.lint_text(text)
    e_exp, w_exp = MEASURED[name]
    if failed == e_exp and warns == w_exp and v == ("FAIL" if e_exp else "PASS"):
        ok("L2 %s -> errors=%s warns=%s" % (name, failed or "-", warns or "-"))
    else:
        no("L2 %s" % name, "got errors=%s warns=%s verdict=%s expected %s/%s" % (
            failed, warns, v, e_exp, w_exp))

# ---------- L3 --fix appends the lint line; idempotent ----------
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "r.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nنص نظيف بلا محافل.\n")
    r = subprocess_lint(["--fix", str(p)])
    t1 = p.read_text()
    if r.returncode == 0 and "lint: PASS" in t1 and "warn: none" in t1 \
            and t1.index("lint: PASS") > t1.index("base_head:"):
        ok("L3 --fix inserts v7.6 lint line into front-matter")
    else:
        no("L3 --fix insert", "rc=%d body=%s" % (r.returncode, t1[:120]))
    r2 = subprocess_lint(["--fix", str(p)])
    if p.read_text() == t1 and r2.returncode == 0:
        ok("L3 --fix idempotent")
    else:
        no("L3 --fix idempotent")
    # corrupt the report under the recorded line -> --check must go stale
    p.write_text(t1.replace("نص نظيف بلا محافل.", "نص فيه `upload/gh-pat.txt` بلا وسم."))
    r3 = subprocess_lint(["--check", str(p)])
    if r3.returncode == 1 and "stale" in r3.stdout:  # full stdout, not truncated
        ok("L4 --check detects stale lint line (warn section drift)")
    else:
        no("L4 --check stale", "rc=%d out=%s" % (r3.returncode, r3.stdout[-200:]))

# ---------- L4 --check missing line ----------
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "r.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nنص نظيف.\n")
    r = subprocess_lint(["--check", str(p)])
    if r.returncode == 1 and "missing lint line" in r.stdout:
        ok("L4 --check missing lint line fails")
    else:
        no("L4 --check missing", "rc=%d out=%s" % (r.returncode, r.stdout[-120:]))
    r = subprocess_lint(["--check", "--fix", str(p)])
    if r.returncode == 2:
        ok("L5 usage error rc=2 for --check+--fix")
    else:
        no("L5 usage rc", "rc=%d" % r.returncode)

# ---------- L6 --json ----------
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "r.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nCLEAR عبر HTML فقط.\n")
    r = subprocess_lint(["--json", str(p)])
    doc = json.loads(r.stdout)
    if r.returncode == 1 and doc["ok"] is False and doc["results"][0]["failed"] == ["a"]:
        ok("L6 --json summary shape (failed = ERROR clauses)")
    else:
        no("L6 --json", "rc=%d doc=%s" % (r.returncode, str(doc)[:150]))

# ---------- L7 placeholder normalization ----------
text = "---\nid: t\nbase_head: 394985f\n---\n\nالعدّاد في `state/quota-google-<date>.json` بلا تنبيه.\n"
v, failed, warns, _ = rl.lint_text(text)
if v == "PASS" and not failed and not warns:
    ok("L7 placeholder path resolves via tracked parent")
else:
    no("L7 placeholder path", "failed=%s warns=%s" % (failed, warns))

# ---------- L8 reused gates ----------
if len(rl.TOKEN_PATTERNS) == 5 and rl.ALLOWED_SYNTHETIC.pattern.startswith(b"ghp_"):
    ok("L8 token patterns imported from tree-token-scan.py")
else:
    no("L8 token patterns import")
if rl.CJK_RANGES and any(lo == 0x4E00 for lo, _ in rl.CJK_RANGES):
    ok("L8 CJK ranges imported from check_cjk.py")
else:
    no("L8 CJK ranges import")

# ---------- L9 lint-line compatibility ----------
with tempfile.TemporaryDirectory() as td:
    # legacy v7.5 PASS line (no warn section) over clean content -> accepted
    p = Path(td) / "legacy-pass.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nنص نظيف بلا محافل.\n"
                 "lint: PASS (a,b,c,d,e,f,g,h) | at: 2026-11-12T00:50:20Z | tool: scripts/report_lint.py\n")
    r = subprocess_lint(["--check", str(p)])
    if r.returncode == 0:
        ok("L9 legacy PASS line accepted leniently under --check")
    else:
        no("L9 legacy PASS", "rc=%d out=%s" % (r.returncode, r.stdout[-160:]))
    # legacy FAIL (a) line covering the computed ERROR clauses -> accepted
    # (unit-level: CLI --check on still-violating content must exit 1)
    legacy_fail_text = ("---\nid: t\nbase_head: 394985f\n---\n\nCLEAR عبر HTML فقط.\n"
                        "lint: FAIL (a,g) | at: 2026-11-12T00:50:20Z | tool: scripts/report_lint.py\n")
    problem = rl.stale_check(legacy_fail_text, "FAIL", ["a"], [])
    if problem is None:
        ok("L9 legacy FAIL line covers computed ERROR clauses (g now WARN)")
    else:
        no("L9 legacy FAIL", problem)
    # v7.6 strict: warn drift is stale
    p3 = Path(td) / "strict.md"
    p3.write_text("---\nid: t\nbase_head: 394985f\n---\n\nنص فيه `upload/gh-pat.txt` بلا وسم.\n"
                  "lint: PASS (a,b,c,d,e,f) | warn: none | at: 2026-11-12T00:50:20Z | tool: scripts/report_lint.py\n")
    r = subprocess_lint(["--check", str(p3)])
    if r.returncode == 1 and "stale" in r.stdout:
        ok("L9 v7.6 line compared strictly (warn drift -> stale)")
    else:
        no("L9 v7.6 strict", "rc=%d out=%s" % (r.returncode, r.stdout[-160:]))

# ---------- L10 severity exits ----------
with tempfile.TemporaryDirectory() as td:
    pw = Path(td) / "warn-only.md"
    pw.write_text("---\nid: t\ndirective: v7.5\nbase_head: 394985f\n---\n\nنص فيه `upload/gh-pat.txt` بلا وسم.\n")
    r = subprocess_lint([str(pw)])
    if r.returncode == 0:
        ok("L10 warn-only report exits 0")
    else:
        no("L10 warn-only rc", "rc=%d" % r.returncode)
    pe = Path(td) / "error.md"
    pe.write_text("---\nid: t\nbase_head: 394985f\n---\n\nCLEAR عبر HTML فقط.\n")
    r = subprocess_lint([str(pe)])
    if r.returncode == 1:
        ok("L10 error report exits 1")
    else:
        no("L10 error rc", "rc=%d" % r.returncode)

print("report-lint tests: %d/%d pass" % (PASS, PASS + FAIL))
sys.exit(1 if FAIL else 0)
