#!/usr/bin/env python3
"""test-report-lint.py — offline tests for scripts/report_lint.py (v7.5 clause 1).

Zero network, zero secrets. Covers:
  L1  fixture matrix: per-clause positives FAIL their clause, negatives PASS
      (fixtures: eval/supervisor-defects/lint/fixtures/, generated by
      scripts/gen_lint_fixtures.sh)
  L2  defect-benchmark integration: the 8 defect cases (أ..ح) + 4 clean
      controls materialized from eval/supervisor-defects/cases/*.yaml and
      linted — expectations are the MEASURED matrix from 2026-11-12
  L3  --fix appends the lint line into the front-matter; idempotent
  L4  --check fails on missing/stale lint line, passes on a fresh one
  L5  exit codes: 0 pass / 1 fail / 2 usage (--check with --fix)
  L6  --json summary shape
  L7  path placeholder normalization (state/quota-google-<date>.json resolves
      via tracked parent dir)
  L8  reused gates: TOKEN_PATTERNS/CJK_RANGES imported from the single-source
      scripts (tree-token-scan.py / check_cjk.py)

Run: python3 team/scripts/test-report-lint.py
"""
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
import report_lint as rl  # noqa: E402

PASS, FAIL = 0, 0
def ok(name):
    global PASS
    PASS += 1
    print("ok  %s" % name)
def no(name, msg=""):
    global FAIL
    FAIL += 1
    print("FAIL %s %s" % (name, msg))

def subprocess_lint(args):
    return subprocess.run([sys.executable, str(REPO / "scripts" / "report_lint.py"), *args],
                          capture_output=True, text=True)

# ---------- L1 fixture matrix ----------
FX = REPO / "eval/supervisor-defects/lint/fixtures"
EXPECTED_POS = {"a": "a", "b": "b", "c": "c", "d": "d", "e": "e", "f": "f", "g": "g", "h": "h"}
for clause in EXPECTED_POS:
    pos = FX / ("%s-pos.md" % clause)
    neg = FX / ("%s-neg.md" % clause)
    v, failed, _ = rl.lint_text(pos.read_text())
    if v == "FAIL" and EXPECTED_POS[clause] in failed:
        ok("L1 %s-pos fails clause %s" % (clause, clause))
    else:
        no("L1 %s-pos" % clause, "verdict=%s failed=%s" % (v, failed))
    v, failed, _ = rl.lint_text(neg.read_text())
    if v == "PASS":
        ok("L1 %s-neg passes" % clause)
    else:
        no("L1 %s-neg" % clause, "failed=%s" % failed)

# ---------- L2 defect-benchmark integration (measured matrix 2026-11-12) ----------
import yaml  # noqa: E402
MEASURED = {
    "defect-01-clear-from-static-html": ["a", "h"],
    "defect-02-verdict-on-old-known-responses": ["a", "h"],
    "defect-03-patch-target-unverified-on-main": [],
    "defect-04-failed-run-as-healthy-heartbeat": ["d"],
    "defect-05-cjk-language-slip": ["e"],
    "defect-06-token-in-conversation": ["h"],
    "defect-07-push-from-stale-base-after-rotation": ["g"],
    "defect-08-agentbox-paths-as-repo-paths": ["h"],
    "defect-09-clean-control-s49": ["h"],
    "defect-10-clean-control-s51": ["a", "h"],
    "defect-11-clean-control-s56": ["h"],
    "defect-12-clean-control-s57": ["h"],
}
CASES = REPO / "eval/supervisor-defects/cases"
for name in sorted(MEASURED):
    doc = yaml.safe_load((CASES / ("%s.yaml" % name)).read_text())
    t = doc.get("defect_type")
    text = doc.get("input", "") if t == "ز" else \
        "---\nid: materialized\ndefect_type: %s\nbase_head: 394985f\n---\n\n%s" % (t, doc.get("input", ""))
    v, failed, _ = rl.lint_text(text)
    if failed == MEASURED[name]:
        ok("L2 %s -> %s" % (name, failed or "PASS"))
    else:
        no("L2 %s" % name, "got %s expected %s" % (failed, MEASURED[name]))

# ---------- L3 --fix appends the lint line; idempotent ----------
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "r.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nنص نظيف بلا محافل.\n")
    r = subprocess_lint(["--fix", str(p)])
    t1 = p.read_text()
    if r.returncode == 0 and "lint: PASS" in t1 and t1.index("lint: PASS") > t1.index("base_head:"):
        ok("L3 --fix inserts lint line into front-matter")
    else:
        no("L3 --fix insert", "rc=%d" % r.returncode)
    r2 = subprocess_lint(["--fix", str(p)])
    if p.read_text() == t1 and r2.returncode == 0:
        ok("L3 --fix idempotent")
    else:
        no("L3 --fix idempotent")
    # corrupt the report under the recorded line -> --check must go stale
    p.write_text(t1.replace("نص نظيف بلا محافل.", "نص فيه `upload/gh-pat.txt` بلا وسم."))
    r3 = subprocess_lint(["--check", str(p)])
    if r3.returncode == 1 and "stale" in r3.stdout:  # full stdout, not truncated
        ok("L4 --check detects stale lint line")
    else:
        no("L4 --check stale", "rc=%d out=%s" % (r3.returncode, r3.stdout[-200:]))

# ---------- L4 --check missing line ----------
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "r.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nنص نظيف.\n")
    r = subprocess_lint(["--check", str(p)])
    if r.returncode == 1 and "missing lint line" in r.stdout:
        ok("L4 --check missing lint line fails")
    else:
        no("L4 --check missing", "rc=%d" % r.returncode)
    r = subprocess_lint(["--check", "--fix", str(p)])
    if r.returncode == 2:
        ok("L5 usage error rc=2 for --check+--fix")
    else:
        no("L5 usage rc", "rc=%d" % r.returncode)

# ---------- L6 --json ----------
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "r.md"
    p.write_text("---\nid: t\nbase_head: 394985f\n---\n\nCLEAR عبر HTML فقط.\n")
    r = subprocess_lint(["--json", str(p)])
    doc = json.loads(r.stdout)
    if r.returncode == 1 and doc["ok"] is False and doc["results"][0]["failed"] == ["a"]:
        ok("L6 --json summary shape")
    else:
        no("L6 --json", "rc=%d doc=%s" % (r.returncode, str(doc)[:150]))

# ---------- L7 placeholder normalization ----------
text = "---\nid: t\nbase_head: 394985f\n---\n\nالعدّاد في `state/quota-google-<date>.json` بلا تنبيه.\n"
v, failed, _ = rl.lint_text(text)
if v == "PASS":
    ok("L7 placeholder path resolves via tracked parent")
else:
    no("L7 placeholder path", "failed=%s" % failed)

# ---------- L8 reused gates ----------
if len(rl.TOKEN_PATTERNS) == 5 and rl.ALLOWED_SYNTHETIC.pattern.startswith(b"ghp_"):
    ok("L8 token patterns imported from tree-token-scan.py")
else:
    no("L8 token patterns import")
if rl.CJK_RANGES and any(lo == 0x4E00 for lo, _ in rl.CJK_RANGES):
    ok("L8 CJK ranges imported from check_cjk.py")
else:
    no("L8 CJK ranges import")

print("report-lint tests: %d/%d pass" % (PASS, PASS + FAIL))
sys.exit(1 if FAIL else 0)
