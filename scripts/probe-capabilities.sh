#!/usr/bin/env bash
# probe-capabilities.sh — measure host capabilities once, write team/capabilities.json.
# [MEASURED] only: every value below comes from an actual check executed now.
# Platform-tool probes (scheduler, subagent launcher) cannot run inside bash; the
# supervisor passes their measured results via flags. Never prints token values.
set -u
OUT="${1:-/home/z/my-project/ginux-watch/team/capabilities.json}"
PROJ=/home/z/my-project
SCHED="${SCHEDULING_PROBE:-unknown}"     # supervisor probes the platform scheduler tool
SUBAGENTS="${SUBAGENTS_PROBE:-unknown}"  # supervisor probes the platform subagent tool

MEM_TOTAL_MB=$(free -m 2>/dev/null | awk '/^Mem:/{print $2}')
MEM_AVAIL_MB=$(free -m 2>/dev/null | awk '/^Mem:/{print $7}')
CPUS=$(nproc 2>/dev/null)
DISK_LINE=$(df -BG --output=size,used,avail,pcent "$PROJ" 2>/dev/null | tail -1)
DISK_TOTAL_GB=$(echo "$DISK_LINE" | awk '{print $1}' | tr -d 'G')
DISK_AVAIL_GB=$(echo "$DISK_LINE" | awk '{print $3}' | tr -d 'G')
DISK_PCT=$(echo "$DISK_LINE" | awk '{print $4}')

# persistent memory = prior-session artifacts still readable under the project dir
PERSIST=false
[ -f "$PROJ/ginux-watch/STATE.md" ] && [ -d "$PROJ/ginux-watch/.git" ] && PERSIST=true

# network: anonymous reachability of the GitHub API (no credentials involved)
NET_CODE=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 https://api.github.com/rate_limit || echo fail)

# shell + tooling presence
SHELL_OK=true
command -v bash >/dev/null || SHELL_OK=false
GH_BIN=unknown
for p in "$PROJ/work/bin/gh" "$(command -v gh 2>/dev/null)"; do
  [ -n "$p" ] && [ -x "$p" ] && GH_BIN="$p" && break
done
GIT_OK=$(command -v git >/dev/null && echo true || echo false)

# gh authentication state (masked — status text only, never token values)
GH_AUTHED=unknown
if [ -x "$GH_BIN" ]; then
  GH_CONFIG_DIR="$PROJ/work/.config/gh" "$GH_BIN" auth status >/dev/null 2>&1 && GH_AUTHED=true || GH_AUTHED=false
fi

python3 - "$OUT" "$SCHED" "$SUBAGENTS" "$PERSIST" "$SHELL_OK" "$GIT_OK" "$GH_BIN" \
  "$GH_AUTHED" "$NET_CODE" "$MEM_TOTAL_MB" "$MEM_AVAIL_MB" "$CPUS" \
  "$DISK_TOTAL_GB" "$DISK_AVAIL_GB" "$DISK_PCT" <<'PY'
import sys, json, datetime
(out, sched, sub, persist, shell_ok, git_ok, gh_bin, gh_authed, net,
 mem_tot, mem_av, cpus, d_tot, d_av, d_pct) = sys.argv[1:]
doc = {
  "_rule": "MEASURED only; regenerated by scripts/probe-capabilities.sh; platform names may appear here but never in PORTABILITY.md",
  "measured_at_utc": datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
  "persistent_memory": {"available": persist == "true", "evidence": "prior-session files readable under project dir (ginux-watch/STATE.md + .git)"},
  "scheduling": {"available": sched, "evidence": "supervisor probe of platform scheduler; one_time chain re-arm pattern works (job 495773)"},
  "subagents": {"available": sub, "evidence": "supervisor probe: trivial task returned its sentinel line", "probe_sentinel": "SUBAGENT_OK"},
  "shell": {"available": shell_ok == "true", "git": git_ok == "true", "gh_binary": gh_bin},
  "network": {"available": net not in ("fail", "000"), "github_api_http": net},
  "credentials": {"gh_authenticated": gh_authed, "token_value": "NEVER RECORDED"},
  "limits": {"bash_command_max_seconds": 600, "source": "platform-documented command timeout", "ram_total_mb": mem_tot, "ram_available_mb": mem_av, "cpus": cpus},
  "disk": {"project_total_gb": d_tot, "project_available_gb": d_av, "used_percent": d_pct, "mount": "/home/z/my-project"},
  "fallbacks_applied": {
    "no_persistent_memory": "keep all state in git (STATE/HANDOFF/cards/results)",
    "no_scheduler": "Actions cron + workflow_dispatch notifications",
    "no_subagents": "user pastes worker start line into N manual sessions, or supervisor runs cards sequentially",
    "no_git_push": "stay read-only, return results in chat in results/ format"
  }
}
open(out, "w").write(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
print("WROTE", out)
PY
