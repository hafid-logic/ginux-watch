def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for cid, task, split, text, t1, t2, source, why in C:
        doc = {
            "id": cid, "task": task, "split": split, "text": text,
            "t1_label": t1 if task == "t1" else None,
            "t2_label": t2 if task == "t2" else None,
            "for_us": t1 in ("request", "directed_at_us") if task == "t1" else (t2 == "needs_supervisor"),
            "source": source, "labeling_rationale": why,
        }
        (OUT / (cid + ".yaml")).write_text(
            yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=100), encoding="utf-8")
    n = len(C)
    t1 = sum(1 for c in C if c[1] == "t1"); t2 = n - t1
    ctrl = sum(1 for c in C if c[2] == "control")
    print("cases:", n, "| t1:", t1, "t2:", t2, "| control:", ctrl, "test:", n - ctrl)

if __name__ == "__main__":
    main()
